# To see the type of the variable in python use type() function.

# <class 'int'>
print("Type of 10", type(10))

# <class 'float'>
print("Type of 10.98", type(10.98))

# <class 'str'>
print("Type of `Hello`", type("Hello"))


# You can put characters on multiple lines
print("""This is to tell
that this thing is working
for me""")

# Above should output:
# 'This is to tell\nthat this thing is working\nfor me'


print("""This is to tell
that this thing is working
for me""", 20 + 2)
